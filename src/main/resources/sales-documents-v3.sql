CREATE OR REPLACE FUNCTION erp_invoice_line_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE invoice_order bigint; source sales_order_lines%ROWTYPE;
BEGIN
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 SELECT sales_order_id INTO invoice_order FROM sales_invoices WHERE id=NEW.invoice_id FOR UPDATE;
 IF NEW.sales_order_line_id IS NOT NULL THEN
   SELECT * INTO source FROM sales_order_lines WHERE id=NEW.sales_order_line_id FOR UPDATE;
   IF source.id IS NULL OR source.sales_order_id<>invoice_order OR source.item_id<>NEW.item_id THEN
     RAISE EXCEPTION 'INVOICE: Dòng hóa đơn phải tham chiếu đúng vật tư và đơn bán.' USING ERRCODE='23514';
   END IF;
 END IF;
 RETURN NEW;
END $$;
