CREATE OR REPLACE FUNCTION erp_return_line_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE parent sales_returns%ROWTYPE; source sales_order_lines%ROWTYPE;
BEGIN
 PERFORM pg_advisory_xact_lock(7821348);
 IF TG_OP<>'INSERT' THEN
   SELECT * INTO parent FROM sales_returns WHERE id=OLD.return_id FOR UPDATE;
   IF parent.status<>'DRAFT' THEN RAISE EXCEPTION 'STOCK: Chỉ được sửa hoặc xóa dòng phiếu trả nháp.' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 SELECT * INTO parent FROM sales_returns WHERE id=NEW.return_id FOR UPDATE;
 IF parent.status<>'DRAFT' THEN RAISE EXCEPTION 'STOCK: Phiếu trả không còn là nháp.' USING ERRCODE='23514'; END IF;
 SELECT * INTO source FROM sales_order_lines WHERE id=NEW.sales_order_line_id FOR UPDATE;
 IF source.id IS NULL OR source.sales_order_id<>parent.sales_order_id THEN
   RAISE EXCEPTION 'STOCK: Dòng hàng phải thuộc đơn bán trên phiếu trả.' USING ERRCODE='23514';
 END IF;
 NEW.item_id=source.item_id;
 IF NEW.quantity>source.quantity THEN RAISE EXCEPTION 'STOCK: Số lượng trả vượt số lượng bán.' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS erp_return_line_guard ON sales_return_lines;
CREATE TRIGGER erp_return_line_guard BEFORE INSERT OR UPDATE OR DELETE ON sales_return_lines FOR EACH ROW EXECUTE FUNCTION erp_return_line_guard();

CREATE OR REPLACE FUNCTION erp_receive_return() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE line record; sold numeric; returned numeric;
BEGIN
 PERFORM pg_advisory_xact_lock(7821348);
 IF TG_OP='INSERT' THEN
   IF NEW.status<>'DRAFT' THEN RAISE EXCEPTION 'STOCK: Tạo phiếu trả ở trạng thái nháp.' USING ERRCODE='23514'; END IF;
   NEW.received_at=NULL; RETURN NEW;
 END IF;
 IF OLD.status<>'DRAFT' THEN
   IF TG_OP='UPDATE' AND NEW IS NOT DISTINCT FROM OLD THEN RETURN OLD; END IF;
   RAISE EXCEPTION 'STOCK: Phiếu đã nhận hoặc đã hủy không được sửa/xóa.' USING ERRCODE='23514';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 IF NEW.sales_order_id<>OLD.sales_order_id AND EXISTS(SELECT 1 FROM sales_return_lines WHERE return_id=OLD.id) THEN
   RAISE EXCEPTION 'STOCK: Xóa các dòng nháp trước khi đổi đơn bán gốc.' USING ERRCODE='23514';
 END IF;
 NEW.received_at=NULL;
 IF NEW.status='RECEIVED' THEN
   IF NOT EXISTS(SELECT 1 FROM sales_return_lines WHERE return_id=NEW.id) THEN RAISE EXCEPTION 'STOCK: Phiếu trả phải có ít nhất một dòng hàng.' USING ERRCODE='23514'; END IF;
   FOR line IN SELECT * FROM sales_return_lines WHERE return_id=NEW.id ORDER BY sales_order_line_id LOOP
     SELECT -s.applied_quantity INTO sold FROM erp_stock_lines s JOIN sales_order_lines l ON l.id=s.source_id
      WHERE s.source_table='sales_order_lines' AND s.source_id=line.sales_order_line_id AND s.item_id=line.item_id AND l.sales_order_id=NEW.sales_order_id;
     SELECT coalesce(sum(l.quantity),0) INTO returned FROM sales_return_lines l JOIN sales_returns r ON r.id=l.return_id
      WHERE l.sales_order_line_id=line.sales_order_line_id AND r.status='RECEIVED';
     IF sold IS NULL OR line.quantity+returned>sold THEN
       RAISE EXCEPTION 'STOCK: Hàng chưa ghi nhận xuất kho hoặc số lượng trả vượt số lượng còn được trả.' USING ERRCODE='23514';
     END IF;
     PERFORM erp_stock_change(line.item_id,NEW.location_id,line.quantity,'sales_returns',NEW.id);
   END LOOP;
   NEW.received_at=CURRENT_TIMESTAMP;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS erp_receive_return ON sales_returns;
CREATE TRIGGER erp_receive_return BEFORE INSERT OR UPDATE OR DELETE ON sales_returns FOR EACH ROW EXECUTE FUNCTION erp_receive_return();

CREATE OR REPLACE FUNCTION erp_return_sale_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(7821348);
 IF TG_TABLE_NAME='sales_orders' THEN
   IF TG_OP='UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status AND NEW.location_id IS NOT DISTINCT FROM OLD.location_id THEN RETURN NEW; END IF;
   IF EXISTS(SELECT 1 FROM sales_returns WHERE sales_order_id=OLD.id AND status='RECEIVED') THEN
     RAISE EXCEPTION 'STOCK: Đơn có hàng đã trả; không được đổi trạng thái, đổi kho hoặc xóa.' USING ERRCODE='23514';
   END IF;
 ELSE
   IF EXISTS(SELECT 1 FROM sales_return_lines l JOIN sales_returns r ON r.id=l.return_id WHERE l.sales_order_line_id=OLD.id AND r.status='RECEIVED') THEN
     RAISE EXCEPTION 'STOCK: Dòng bán đã có hàng trả; không được sửa/xóa.' USING ERRCODE='23514';
   END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS erp_return_sale_guard ON sales_orders;
DROP TRIGGER IF EXISTS erp_return_sale_guard ON sales_order_lines;
CREATE TRIGGER erp_return_sale_guard BEFORE UPDATE OR DELETE ON sales_orders FOR EACH ROW EXECUTE FUNCTION erp_return_sale_guard();
CREATE TRIGGER erp_return_sale_guard BEFORE UPDATE OR DELETE ON sales_order_lines FOR EACH ROW EXECUTE FUNCTION erp_return_sale_guard();

