CREATE TRIGGER erp_invoice_line_guard BEFORE INSERT OR UPDATE OR DELETE ON sales_invoice_lines FOR EACH ROW EXECUTE FUNCTION erp_invoice_line_guard();

CREATE OR REPLACE FUNCTION erp_invoice_line_totals() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE doc_id bigint;
BEGIN
 doc_id=CASE WHEN TG_OP='DELETE' THEN OLD.invoice_id ELSE NEW.invoice_id END;
 UPDATE sales_invoices SET vat_amount=totals.vat_amount,total_amount=totals.total_amount
 FROM (
   SELECT coalesce(sum(vat_amount),0) AS vat_amount,
          coalesce(sum(line_amount+vat_amount),0) AS total_amount
   FROM sales_invoice_lines WHERE sales_invoice_lines.invoice_id=doc_id
 ) totals WHERE sales_invoices.id=doc_id;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS erp_invoice_line_totals ON sales_invoice_lines;
CREATE TRIGGER erp_invoice_line_totals AFTER INSERT OR UPDATE OR DELETE ON sales_invoice_lines FOR EACH ROW EXECUTE FUNCTION erp_invoice_line_totals();

CREATE OR REPLACE FUNCTION erp_sales_header_from_return() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE customer bigint; order_currency varchar(20); doc_no varchar(50);
BEGIN
 IF TG_OP='DELETE' THEN
   DELETE FROM sales_headers WHERE sales_return_id=OLD.id;
   RETURN OLD;
 END IF;
 SELECT customer_id,currency_code INTO customer,order_currency FROM sales_orders WHERE id=NEW.sales_order_id;
 doc_no=NEW.return_no;
 IF EXISTS(SELECT 1 FROM sales_headers WHERE quote_no=doc_no AND sales_return_id IS DISTINCT FROM NEW.id) THEN
   doc_no='SR-'||NEW.return_no;
 END IF;
 INSERT INTO sales_headers(document_type,quote_no,customer_id,location_id,order_date,currency_code,status,notes,related_sales_order_id,sales_return_id)
 VALUES('RETURN_ORDER',doc_no,customer,NEW.location_id,NEW.return_date,coalesce(order_currency,'VND'),'CONVERTED',NEW.reason,NEW.sales_order_id,NEW.id)
 ON CONFLICT (sales_return_id) DO UPDATE SET location_id=EXCLUDED.location_id,order_date=EXCLUDED.order_date,
   status=EXCLUDED.status,notes=EXCLUDED.notes,related_sales_order_id=EXCLUDED.related_sales_order_id,updated_at=CURRENT_TIMESTAMP;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS erp_sales_header_from_return ON sales_returns;
CREATE TRIGGER erp_sales_header_from_return AFTER INSERT OR UPDATE OR DELETE ON sales_returns FOR EACH ROW EXECUTE FUNCTION erp_sales_header_from_return();

CREATE OR REPLACE FUNCTION erp_sales_header_from_invoice() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE order_location bigint; doc_no varchar(50);
BEGIN
 IF TG_OP='DELETE' THEN
   DELETE FROM sales_headers WHERE sales_invoice_id=OLD.id;
   RETURN OLD;
 END IF;
 SELECT location_id INTO order_location FROM sales_orders WHERE id=NEW.sales_order_id;
 doc_no=NEW.invoice_no;
 IF EXISTS(SELECT 1 FROM sales_headers WHERE quote_no=doc_no AND sales_invoice_id IS DISTINCT FROM NEW.id) THEN
   doc_no='SI-'||NEW.invoice_no;
 END IF;
 INSERT INTO sales_headers(document_type,quote_no,customer_id,location_id,order_date,currency_code,status,
   subtotal,vat_amount,total_amount,related_sales_order_id,sales_invoice_id)
 VALUES('INVOICE',doc_no,NEW.customer_id,order_location,NEW.invoice_date,coalesce(NEW.currency_code,'VND'),'CONVERTED',
   greatest(NEW.total_amount-NEW.vat_amount,0),NEW.vat_amount,NEW.total_amount,NEW.sales_order_id,NEW.id)
 ON CONFLICT (sales_invoice_id) DO UPDATE SET customer_id=EXCLUDED.customer_id,location_id=EXCLUDED.location_id,
   order_date=EXCLUDED.order_date,currency_code=EXCLUDED.currency_code,subtotal=EXCLUDED.subtotal,
   vat_amount=EXCLUDED.vat_amount,total_amount=EXCLUDED.total_amount,related_sales_order_id=EXCLUDED.related_sales_order_id,
   updated_at=CURRENT_TIMESTAMP;
 RETURN NEW;
END $$;
