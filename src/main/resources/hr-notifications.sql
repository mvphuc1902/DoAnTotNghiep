CREATE TABLE IF NOT EXISTS hr_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint UNIQUE REFERENCES hr_posts(id) ON DELETE CASCADE,
    job_post_id bigint UNIQUE REFERENCES hr_job_posts(id) ON DELETE CASCADE,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((post_id IS NULL) <> (job_post_id IS NULL))
);
CREATE TABLE IF NOT EXISTS hr_notification_reads (
    notification_id bigint NOT NULL REFERENCES hr_notifications(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    read_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (notification_id,user_id)
);
CREATE INDEX IF NOT EXISTS hr_notification_reads_user_idx ON hr_notification_reads(user_id);

CREATE OR REPLACE FUNCTION hr_notify_publication() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status<>'PUBLISHED' THEN RETURN NEW; END IF;
    IF TG_OP='UPDATE' AND OLD.status='PUBLISHED' THEN RETURN NEW; END IF;
    IF TG_TABLE_NAME='hr_posts' THEN
        INSERT INTO hr_notifications(post_id) VALUES(NEW.id) ON CONFLICT(post_id) DO NOTHING;
    ELSE
        INSERT INTO hr_notifications(job_post_id) VALUES(NEW.id) ON CONFLICT(job_post_id) DO NOTHING;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS hr_notify_publication ON hr_posts;
CREATE TRIGGER hr_notify_publication AFTER INSERT OR UPDATE OF status ON hr_posts
FOR EACH ROW EXECUTE FUNCTION hr_notify_publication();
DROP TRIGGER IF EXISTS hr_notify_publication ON hr_job_posts;
CREATE TRIGGER hr_notify_publication AFTER INSERT OR UPDATE OF status ON hr_job_posts
FOR EACH ROW EXECUTE FUNCTION hr_notify_publication();
