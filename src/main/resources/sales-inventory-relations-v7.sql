DECLARE table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'sales_headers', 'sales_quote_lines', 'sales_order_lines',
        'sales_return_lines', 'sales_invoice_lines'
    ] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS zz_sales_lines_sync ON %I', table_name);
        EXECUTE format(
            'CREATE TRIGGER zz_sales_lines_sync AFTER INSERT OR UPDATE OR DELETE ON %I '
            'FOR EACH ROW EXECUTE FUNCTION erp_refresh_sales_line_trigger()',
            table_name
        );
    END LOOP;
END $$;
