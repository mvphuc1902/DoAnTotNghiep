DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM inventory stock
        LEFT JOIN items item ON item.id = stock.item_id
        WHERE stock.item_id IS NOT NULL AND item.id IS NULL
    ) THEN
        RAISE EXCEPTION 'Cannot add inventory.item_id foreign key: orphan item references exist.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'inventory'::regclass
          AND confrelid = 'items'::regclass
          AND contype = 'f'
          AND conkey = ARRAY[(SELECT attnum FROM pg_attribute
                              WHERE attrelid = 'inventory'::regclass AND attname = 'item_id')]
    ) THEN
        ALTER TABLE inventory
            ADD CONSTRAINT inventory_item_id_fkey FOREIGN KEY (item_id) REFERENCES items(id);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS sales_quote_lines (
    id bigserial PRIMARY KEY,
    sales_header_id bigint NOT NULL REFERENCES sales_headers(id),
    line_no integer NOT NULL,
    item_id bigint NOT NULL REFERENCES items(id),
    description varchar(255),
    unit_of_measure varchar(255),
    quantity numeric(18,3) NOT NULL CHECK (quantity > 0),
    unit_price numeric(18,2) NOT NULL CHECK (unit_price >= 0),
    discount_percent numeric(5,2) NOT NULL CHECK (discount_percent BETWEEN 0 AND 100),
    vat_percent numeric(5,2) NOT NULL CHECK (vat_percent BETWEEN 0 AND 100),
    UNIQUE (sales_header_id, line_no)
);

CREATE TABLE IF NOT EXISTS sales_invoices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no varchar(50) NOT NULL UNIQUE,
    sales_order_id bigint NOT NULL REFERENCES sales_orders(id),
    customer_id bigint NOT NULL REFERENCES customers(id),
    invoice_date date NOT NULL DEFAULT CURRENT_DATE,
    posting_date date NOT NULL DEFAULT CURRENT_DATE,
    currency_code varchar(20) NOT NULL DEFAULT 'VND',
    total_amount numeric(18,2) NOT NULL DEFAULT 0,
    vat_amount numeric(18,2) NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sales_invoice_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES sales_invoices(id),
    line_no integer NOT NULL,
    sales_order_line_id bigint REFERENCES sales_order_lines(id),
    item_id bigint NOT NULL REFERENCES items(id),
    description varchar(255),
    quantity numeric(18,3) NOT NULL CHECK (quantity > 0),
    unit_price numeric(18,2) NOT NULL CHECK (unit_price >= 0),
    vat_percent numeric(5,2) NOT NULL DEFAULT 0 CHECK (vat_percent BETWEEN 0 AND 100),
    vat_amount numeric(18,2) NOT NULL DEFAULT 0,
    line_amount numeric(18,2) NOT NULL DEFAULT 0,
    UNIQUE (invoice_id, line_no)
);

CREATE TABLE IF NOT EXISTS sales_return_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id bigint NOT NULL REFERENCES sales_returns(id),
    sales_order_line_id bigint NOT NULL REFERENCES sales_order_lines(id),
    item_id bigint NOT NULL REFERENCES items(id),
    quantity numeric(18,3) NOT NULL CHECK (quantity > 0),
    UNIQUE (return_id, sales_order_line_id)
);

CREATE INDEX IF NOT EXISTS sales_return_lines_order_line_idx
    ON sales_return_lines(sales_order_line_id);

