CREATE OR REPLACE FUNCTION sync_purchase_receipt_quantity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    purchase_line_id bigint;
BEGIN
    IF TG_OP='UPDATE' OR TG_OP='DELETE' THEN
        purchase_line_id := OLD.purchase_order_line_id;
        IF purchase_line_id IS NOT NULL THEN
            UPDATE purchase_lines line SET quantity_received=(
                SELECT coalesce(sum(receipt_line.quantity),0)
                FROM purchase_receipt_lines receipt_line
                WHERE receipt_line.purchase_order_line_id=purchase_line_id
            ) WHERE line.id=purchase_line_id AND line.document_type='ORDER';
        END IF;
    END IF;
    IF TG_OP='INSERT' OR TG_OP='UPDATE' THEN
        purchase_line_id := NEW.purchase_order_line_id;
    ELSE
        purchase_line_id := NULL;
    END IF;
    IF purchase_line_id IS NOT NULL THEN
        UPDATE purchase_lines line SET quantity_received=(
            SELECT coalesce(sum(receipt_line.quantity),0)
            FROM purchase_receipt_lines receipt_line
            WHERE receipt_line.purchase_order_line_id=purchase_line_id
        ) WHERE line.id=purchase_line_id AND line.document_type='ORDER';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS purchase_receipt_quantity_sync ON purchase_receipt_lines;
CREATE TRIGGER purchase_receipt_quantity_sync
AFTER INSERT OR UPDATE OR DELETE ON purchase_receipt_lines
FOR EACH ROW EXECUTE FUNCTION sync_purchase_receipt_quantity();

