CREATE OR REPLACE FUNCTION sync_purchase_invoiced_quantity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    source_line_id bigint;
BEGIN
    IF TG_OP='UPDATE' OR TG_OP='DELETE' THEN
        source_line_id := OLD.source_purchase_line_id;
        IF source_line_id IS NOT NULL THEN
            UPDATE purchase_lines line SET quantity_invoiced=(
                SELECT coalesce(sum(invoice_line.quantity),0)
                FROM purchase_lines invoice_line
                WHERE invoice_line.source_purchase_line_id=source_line_id
                  AND invoice_line.document_type='INVOICE'
            ) WHERE line.id=source_line_id AND line.document_type='ORDER';
        END IF;
    END IF;
    IF TG_OP='INSERT' OR TG_OP='UPDATE' THEN
        source_line_id := NEW.source_purchase_line_id;
    ELSE
        source_line_id := NULL;
    END IF;
    IF source_line_id IS NOT NULL THEN
        UPDATE purchase_lines line SET quantity_invoiced=(
            SELECT coalesce(sum(invoice_line.quantity),0)
            FROM purchase_lines invoice_line
            WHERE invoice_line.source_purchase_line_id=source_line_id
              AND invoice_line.document_type='INVOICE'
        ) WHERE line.id=source_line_id AND line.document_type='ORDER';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS purchase_invoice_quantity_sync ON purchase_lines;
CREATE TRIGGER purchase_invoice_quantity_sync
AFTER INSERT OR UPDATE OR DELETE ON purchase_lines
FOR EACH ROW EXECUTE FUNCTION sync_purchase_invoiced_quantity();

