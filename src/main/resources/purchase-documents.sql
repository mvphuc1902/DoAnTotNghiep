CREATE SEQUENCE IF NOT EXISTS purchase_document_no_seq;

CREATE TABLE IF NOT EXISTS purchase_headers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type varchar(20) NOT NULL CHECK (document_type IN ('ORDER', 'QUOTE', 'INVOICE')),
    document_no varchar(30) NOT NULL,
    vendor_id bigint NOT NULL REFERENCES vendors(id),
    order_date date NOT NULL DEFAULT CURRENT_DATE,
    posting_date date,
    requested_receipt_date date,
    promised_receipt_date date,
    vendor_reference varchar(100),
    external_document_no varchar(100),
    currency_code varchar(10) NOT NULL DEFAULT 'VND',
    payment_terms_code varchar(20),
    shipment_method_code varchar(20),
    salesperson_code varchar(30),
    location_code varchar(20),
    status varchar(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'OPEN', 'RELEASED', 'POSTED', 'CANCELLED')),
    discount_percent numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
    discount_amount numeric(18,2) NOT NULL DEFAULT 0,
    vat_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_amount numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (document_type, document_no)
);

CREATE INDEX IF NOT EXISTS idx_purchase_headers_type_date
    ON purchase_headers(document_type, order_date DESC);
CREATE INDEX IF NOT EXISTS idx_purchase_headers_vendor
    ON purchase_headers(vendor_id, order_date DESC);

CREATE TABLE IF NOT EXISTS purchase_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no varchar(30) NOT NULL UNIQUE,
    purchase_order_id bigint,
    vendor_id bigint NOT NULL REFERENCES vendors(id),
    receipt_date date NOT NULL DEFAULT CURRENT_DATE,
    location_code varchar(20),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS purchase_receipt_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL REFERENCES purchase_receipts(id) ON DELETE CASCADE,
    line_no integer NOT NULL CHECK (line_no > 0),
    purchase_order_line_id bigint,
    item_id bigint NOT NULL REFERENCES items(id),
    quantity numeric(18,3) NOT NULL CHECK (quantity > 0),
    unit_of_measure varchar(20),
    location_code varchar(20),
    UNIQUE (receipt_id, line_no)
);

ALTER TABLE purchase_receipts ADD COLUMN IF NOT EXISTS purchase_order_id bigint;
ALTER TABLE purchase_receipt_lines ADD COLUMN IF NOT EXISTS purchase_order_line_id bigint;

CREATE TABLE IF NOT EXISTS purchase_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_header_id bigint NOT NULL REFERENCES purchase_headers(id) ON DELETE CASCADE,
    document_type varchar(20) NOT NULL CHECK (document_type IN ('ORDER', 'QUOTE', 'INVOICE')),
    document_no varchar(30) NOT NULL,
    line_no integer NOT NULL CHECK (line_no > 0),
    item_id bigint REFERENCES items(id),
    description varchar(250) NOT NULL,
    location_code varchar(20),
    unit_of_measure varchar(20),
    quantity numeric(18,3) NOT NULL CHECK (quantity > 0),
    quantity_received numeric(18,3) NOT NULL DEFAULT 0,
    quantity_invoiced numeric(18,3) NOT NULL DEFAULT 0,
    unit_price numeric(18,2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
    discount_percent numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
    discount_amount numeric(18,2) NOT NULL DEFAULT 0,
    vat_percent numeric(5,2) NOT NULL DEFAULT 0 CHECK (vat_percent BETWEEN 0 AND 100),
    vat_amount numeric(18,2) NOT NULL DEFAULT 0,
    line_amount numeric(18,2) NOT NULL DEFAULT 0,
    source_purchase_line_id bigint REFERENCES purchase_lines(id),
    purchase_receipt_line_id bigint REFERENCES purchase_receipt_lines(id),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (purchase_header_id, line_no),
    CHECK (document_type = 'INVOICE' OR purchase_receipt_line_id IS NULL)
);

CREATE INDEX IF NOT EXISTS idx_purchase_lines_header
    ON purchase_lines(purchase_header_id, line_no);
CREATE INDEX IF NOT EXISTS idx_purchase_lines_receipt_line
    ON purchase_lines(purchase_receipt_line_id)
    WHERE purchase_receipt_line_id IS NOT NULL;

CREATE TEMP TABLE purchase_invoice_migration_map(old_id bigint PRIMARY KEY, new_id bigint) ON COMMIT DROP;
DO $$
DECLARE
    old_invoice record;
    new_invoice_id bigint;
    legacy_tables_exist boolean;
BEGIN
    legacy_tables_exist := to_regclass('public.purchase_orders') IS NOT NULL
        OR to_regclass('public.purchase_order_lines') IS NOT NULL
        OR to_regclass('public.purchase_invoices') IS NOT NULL
        OR to_regclass('public.purchase_invoice_lines') IS NOT NULL;
    IF legacy_tables_exist AND (
        to_regclass('public.purchase_orders') IS NULL
        OR to_regclass('public.purchase_order_lines') IS NULL
        OR to_regclass('public.purchase_invoices') IS NULL
        OR to_regclass('public.purchase_invoice_lines') IS NULL
    ) THEN
        RAISE EXCEPTION 'Legacy Purchase tables are incomplete; refusing to remove or partially migrate them.';
    END IF;
    IF legacy_tables_exist THEN
        INSERT INTO purchase_headers(
            id, document_type, document_no, vendor_id, order_date, posting_date, requested_receipt_date,
            promised_receipt_date, vendor_reference, external_document_no, currency_code,
            payment_terms_code, shipment_method_code, salesperson_code, location_code, status,
            discount_percent, discount_amount, vat_amount, total_amount, created_at, updated_at
        )
        SELECT id, 'ORDER', order_no, vendor_id, order_date, posting_date, requested_receipt_date,
               promised_receipt_date, vendor_reference, external_document_no, currency_code,
               payment_terms_code, shipment_method_code, salesperson_code, location_code,
               CASE WHEN status IN ('DRAFT', 'OPEN', 'RELEASED', 'POSTED', 'CANCELLED') THEN status
                    WHEN status IN ('INVOICED', 'RECEIVED', 'PARTIALLY_RECEIVED', 'CLOSED') THEN 'POSTED'
                    ELSE 'DRAFT' END,
               coalesce(discount_percent, 0), coalesce(discount_amount, 0), coalesce(vat_amount, 0),
               coalesce(total_amount, 0), created_at, updated_at
        FROM purchase_orders
        ON CONFLICT (document_type, document_no) DO NOTHING;

        PERFORM setval(pg_get_serial_sequence('purchase_headers', 'id'),
                       greatest(coalesce((SELECT max(id) FROM purchase_headers), 1), 1),
                       EXISTS (SELECT 1 FROM purchase_headers));

        INSERT INTO purchase_lines(
            id, purchase_header_id, document_type, document_no, line_no, item_id, description,
            location_code, unit_of_measure, quantity, quantity_received, quantity_invoiced,
            unit_price, discount_percent, discount_amount, vat_percent, vat_amount, line_amount
        )
        SELECT old_line.id, old_line.purchase_order_id, 'ORDER', header.document_no, old_line.line_no,
               old_line.item_id, old_line.description, old_line.location_code, old_line.unit_of_measure,
               old_line.quantity, old_line.quantity_received, old_line.quantity_invoiced,
               old_line.unit_price, old_line.discount_percent, old_line.discount_amount,
               old_line.vat_percent, old_line.vat_amount, old_line.line_amount
        FROM purchase_order_lines old_line
        JOIN purchase_headers header ON header.id=old_line.purchase_order_id AND header.document_type='ORDER'
        ON CONFLICT (id) DO NOTHING;

        PERFORM setval(pg_get_serial_sequence('purchase_lines', 'id'),
                       greatest(coalesce((SELECT max(id) FROM purchase_lines), 1), 1),
                       EXISTS (SELECT 1 FROM purchase_lines));

        FOR old_invoice IN SELECT * FROM purchase_invoices ORDER BY id LOOP
            INSERT INTO purchase_headers(
                document_type, document_no, vendor_id, order_date, posting_date,
                currency_code, status, vat_amount, total_amount, created_at, updated_at
            )
            VALUES (
                'INVOICE', old_invoice.invoice_no, old_invoice.vendor_id,
                old_invoice.invoice_date, old_invoice.posting_date,
                coalesce(old_invoice.currency_code, 'VND'), 'POSTED',
                coalesce(old_invoice.vat_amount, 0), coalesce(old_invoice.total_amount, 0),
                old_invoice.created_at, old_invoice.created_at
            )
            ON CONFLICT (document_type, document_no) DO UPDATE SET document_no=EXCLUDED.document_no
            RETURNING id INTO new_invoice_id;
            INSERT INTO purchase_invoice_migration_map(old_id, new_id)
            VALUES (old_invoice.id, new_invoice_id);
        END LOOP;

        INSERT INTO purchase_lines(
            purchase_header_id, document_type, document_no, line_no, item_id, description,
            quantity, quantity_invoiced, unit_price, discount_percent, discount_amount,
            vat_percent, vat_amount, line_amount, source_purchase_line_id
        )
        SELECT invoice_map.new_id, 'INVOICE', header.document_no, old_line.line_no, old_line.item_id,
               old_line.description, old_line.quantity, old_line.quantity, old_line.unit_price,
               0, 0, coalesce(old_line.vat_percent, 0), coalesce(old_line.vat_amount, 0),
               coalesce(old_line.line_amount, 0), old_line.purchase_order_line_id
        FROM purchase_invoice_lines old_line
        JOIN purchase_invoice_migration_map invoice_map ON invoice_map.old_id=old_line.invoice_id
        JOIN purchase_headers header ON header.id=invoice_map.new_id;
    END IF;
END $$;

